bool validateOutputTilePatternV1(const OutputTilePatternV1 &tiles,
                                 std::string &error) {
  error.clear();
  if (tiles.tile_m < 1 || tiles.tile_m > 64 ||
      tiles.tile_n < 1 || tiles.tile_n > 64)
    return reject(error, "M/N tile parameters must both be integers in 1..64");
  return true;
}

std::string strictGemmOutputTileTransformV1(const OutputTilePatternV1 &tiles,
                                           std::string &error) {
  if (!validateOutputTilePatternV1(tiles, error)) return {};
  return "module attributes {transform.with_named_sequence} {\n"
      "  transform.named_sequence @__transform_main(%root: !transform.any_op {transform.readonly}) {\n"
      "    %matmul = transform.structured.match ops{[\"linalg.matmul\"]} in %root : (!transform.any_op) -> !transform.any_op\n"
      "    %tiled, %m, %n = transform.structured.tile_using_for %matmul tile_sizes [" +
      std::to_string(tiles.tile_m) + ", " + std::to_string(tiles.tile_n) +
      ", 0] : (!transform.any_op) -> (!transform.any_op, !transform.op<\"scf.for\">, !transform.op<\"scf.for\">)\n"
      "    %generic = transform.structured.generalize %tiled : (!transform.any_op) -> !transform.any_op\n"
      "    %scheduled = transform.structured.interchange %generic iterator_interchange = [0, 2, 1] : (!transform.any_op) -> !transform.any_op\n"
      "    transform.yield\n  }\n}\n";
}

OwningOpRef<ModuleOp> deriveStrictGemmOutputTiledV1(
    ModuleOp canonical_bufferized, const OutputTilePatternV1 &tiles,
    std::string &error) {
  if (!validateOutputTilePatternV1(tiles, error) ||
      !cpu_candidate::verifyStrictGemmBufferizedV1(canonical_bufferized, error))
    return {};
  auto result = runSchedule(canonical_bufferized, tiles, error);
  if (!result || !verifyStrictGemmOutputTiledV1(*result, tiles, error)) return {};
  return result;
}

bool verifyStrictGemmOutputTiledV1(ModuleOp scheduled,
                                  const OutputTilePatternV1 &tiles,
                                  std::string &error) {
  if (!validateOutputTilePatternV1(tiles, error) ||
      !scalarEnvelope(scheduled, tiles, error)) return false;
  auto original = cpu_candidate::buildStrictGemmStagesV1(*scheduled.getContext());
  if (!original) { error = original.error; return false; }
  auto expected = runSchedule(*original.bufferized, tiles, error);
  if (!expected) return false;
  if (!OperationEquivalence::isEquivalentTo(scheduled, *expected,
                                           OperationEquivalence::IgnoreLocations))
    return reject(error, "scheduled payload differs from parameter-bound upstream replay");
  return true;
}

std::string strictGemmOutputPeelNTransformV1(const OutputTilePatternV1 &tiles,
                                           std::string &error) {
  auto text = strictGemmOutputTileTransformV1(tiles, error);
  if (text.empty() || tiles.tile_n == 1) return text;
  const auto yield = text.find("    transform.yield\n");
  if (yield == std::string::npos) {
    reject(error, "closed peel-N Transform template changed");
    return {};
  }
  text.insert(yield,
      "    %full_n, %tail_n = transform.loop.peel %n : (!transform.op<\"scf.for\">) -> (!transform.op<\"scf.for\">, !transform.op<\"scf.for\">)\n");
  return text;
}

OwningOpRef<ModuleOp> deriveStrictGemmOutputPeelNV1(
    ModuleOp canonical_bufferized, const OutputTilePatternV1 &tiles,
    std::string &error) {
  if (!validateOutputTilePatternV1(tiles, error) ||
      !cpu_candidate::verifyStrictGemmBufferizedV1(canonical_bufferized, error))
    return {};
  auto result = runPeelNSchedule(canonical_bufferized, tiles, error);
  if (!result || !verifyStrictGemmOutputPeelNV1(*result, tiles, error)) return {};
  return result;
}

bool verifyStrictGemmOutputPeelNV1(ModuleOp scheduled,
                                  const OutputTilePatternV1 &tiles,
                                  std::string &error) {
  if (!validateOutputTilePatternV1(tiles, error)) return false;
  if (!peelScalarEnvelope(scheduled, tiles, error)) {
    // Stable stage distinction for independent valid-mutant tests: replay
    // refusal must never masquerade as evidence of the scalar/domain proof.
    error = "peeled scalar envelope: " + error;
    return false;
  }
  auto original = cpu_candidate::buildStrictGemmStagesV1(*scheduled.getContext());
  if (!original) { error = original.error; return false; }
  auto expected = runPeelNSchedule(*original.bufferized, tiles, error);
  if (!expected) return false;
  if (!OperationEquivalence::isEquivalentTo(scheduled, *expected,
                                           OperationEquivalence::IgnoreLocations))
    return reject(error, "peeled payload differs from parameter-bound upstream replay");
  return true;
}

